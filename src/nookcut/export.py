"""NLE export: CMX3600 EDL (with M2 speed lines) and a DaVinci Resolve Lua builder.

The Lua script runs inside Resolve (Workspace > Scripts, or Workspace > Console > Lua with dofile),
which also works in the free edition, where external scripting is unavailable.
"""
from __future__ import annotations

import os

from .edit import timeline, total
from .probe import timecode_seconds

FPS_CHOICES = (24, 25, 30, 50, 60)


def _tc(seconds: float, fps: int) -> str:
    f = round(seconds * fps)
    return f"{f // (3600 * fps):02d}:{f // (60 * fps) % 60:02d}:{f // fps % 60:02d}:{f % fps:02d}"


def edl(edit: dict, fps: int, title: str = "NookCut Edit") -> str:
    offset = timecode_seconds(edit.get("source_timecode", "00:00:00:00"), edit.get("source_fps", fps))
    clip = os.path.basename(edit["source"])
    lines = [f"TITLE: {title}", "FCM: NON-DROP FRAME", ""]
    for n, (start, dur, s) in enumerate(timeline(edit), 1):
        a, b = offset + s["src_in"], offset + s["src_out"]
        lines.append(f"{n:03d}  AX       V     C        {_tc(a, fps)} {_tc(b, fps)} "
                     f"{_tc(3600 + start, fps)} {_tc(3600 + start + dur, fps)}")
        lines.append(f"* FROM CLIP NAME: {clip}")
        if s["speed"] != 1:
            lines.append(f"M2   AX       {fps * s['speed']:05.1f}                {_tc(a, fps)}")
        lines.append("")
    return "\n".join(lines)


LUA = r'''-- Generated by nookcut. Builds the edit inside the CURRENT project; only adds a bin + timelines.
local KIT = [[{kit}]]
local SOURCE = [[{source}]]
local RENDER = [[{render}]]
local MUSIC = [[{music}]]
local NAME = [[{name}]]
local W, H, LEN = "{w}", "{h}", {length}
local logf = io.open(KIT .. "/resolve_log.txt", "w")
local function log(...)
    local t = {{}}
    for i = 1, select("#", ...) do t[#t + 1] = tostring(select(i, ...)) end
    local line = table.concat(t, " "); print(line); logf:write(line .. "\n"); logf:flush()
end
local resolve = resolve or Resolve()
local pm = resolve:GetProjectManager()
local proj = pm:GetCurrentProject()
local mp = proj:GetMediaPool()
local fps = tonumber(proj:GetSetting("timelineFrameRate")) or 60
log("project", proj:GetName(), "fps", fps)
local bin = mp:AddSubFolder(mp:GetRootFolder(), NAME)
if bin then mp:SetCurrentFolder(bin) end
local function import(path)
    if path == "" then return nil end
    local items = mp:ImportMedia({{ path }})
    if items and items[1] then return items[1] end
    log("import failed", path)
end
import(SOURCE)
local final = import(RENDER)
local music = import(MUSIC)
local function shape(tl)
    tl:SetSetting("useCustomSettings", "1")
    tl:SetSetting("timelineResolutionWidth", W)
    tl:SetSetting("timelineResolutionHeight", H)
end
if final then
    local tl = mp:CreateEmptyTimeline(NAME .. " - FINAL")
    proj:SetCurrentTimeline(tl); shape(tl)
    log("FINAL items", #(mp:AppendToTimeline({{ final }}) or {{}}))
end
local edlfps = 60
for _, f in ipairs({{ 24, 25, 30, 50, 60 }}) do if math.abs(fps - f) < 1.1 then edlfps = f end end
local tl = mp:ImportTimelineFromFile(KIT .. "/cut_" .. edlfps .. ".edl",
    {{ timelineName = NAME .. " - EDITABLE", importSourceClips = false }})
if tl then
    proj:SetCurrentTimeline(tl); shape(tl)
    local items = tl:GetItemListInTrack("video", 1) or {{}}
    log("EDITABLE items", #items, "expected {count}")
    for _, it in ipairs(items) do it:SetProperty("ZoomX", {zoom}); it:SetProperty("ZoomY", {zoom}) end
    if music then
        mp:AppendToTimeline({{ {{ mediaPoolItem = music, startFrame = 0, endFrame = math.floor(LEN * fps),
            trackIndex = 1, mediaType = 2, recordFrame = tl:GetStartFrame() }} }})
    end
    local n = 0
    for line in io.lines(KIT .. "/markers.txt") do
        local t, color, txt = line:match("([^\t]+)\t([^\t]+)\t(.+)")
        if t and tl:AddMarker(math.floor(tonumber(t) * fps + 0.5), color, txt, "Caption: " .. txt, 1) then n = n + 1 end
    end
    log("markers", n)
else
    log("EDL import failed at fps", edlfps)
end
pm:SaveProject()
log("DONE")
logf:close()
'''

MARKER_COLORS = {"hook": "Red", "intro": "Blue", "death": "Red", "card": "Yellow", "highlight": "Green",
                 "slowmo": "Green", "finisher": "Red", "outro": "Purple", "end": "Cyan"}


def resolve_kit(edit: dict, kit_dir: str, render_path: str = "", music_path: str = "",
                name: str = "NookCut Short") -> dict:
    """Write cut_<fps>.edl files, markers.txt, build_timeline.lua and (with speech) captions.srt."""
    os.makedirs(kit_dir, exist_ok=True)
    for fps in FPS_CHOICES:
        with open(os.path.join(kit_dir, f"cut_{fps}.edl"), "w") as f:
            f.write(edl(edit, fps, name))
    with open(os.path.join(kit_dir, "markers.txt"), "w", encoding="utf-8") as f:
        for start, _, s in timeline(edit):
            txt = " / ".join(x for x in (s["top"].replace("|", " "), s["bottom"]) if x)
            if txt:
                f.write(f"{start:.3f}\t{MARKER_COLORS.get(s['kind'], 'Blue')}\t{txt}\n")
    # vertical: show a 1.2:1 band of the 16:9 source across the full width, like the ffmpeg render
    zoom = round((16 / 9) / 1.2, 3) if edit["orientation"] == "vertical" else 1.0
    lua = LUA.format(kit=os.path.abspath(kit_dir), source=edit["source"], render=render_path, music=music_path,
                     name=name, w=edit["width"], h=edit["height"], length=total(edit),
                     count=len(edit["segments"]), zoom=zoom)
    lua_path = os.path.join(kit_dir, "build_timeline.lua")
    with open(lua_path, "w", encoding="utf-8") as f:
        f.write(lua)
    out = {"kit": kit_dir, "lua": lua_path,
           "how_to_run": f'In Resolve: Workspace > Console > Lua, then: dofile("{os.path.abspath(lua_path)}")'}
    if edit.get("subtitles"):
        from .subtitles import srt
        out["captions_srt"] = os.path.join(kit_dir, "captions.srt")
        with open(out["captions_srt"], "w", encoding="utf-8") as f:
            f.write(srt(edit))
    return out
